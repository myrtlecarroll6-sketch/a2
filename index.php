        <div class="knit-faq-accordion">
          <div class="faq-knit-item active">
            <button class="faq-knit-btn">Why does 15.5-micron merino wool feel completely itch-free against the skin? <span class="faq-toggle-icon">+</span></button>
            <div class="faq-knit-content">
              Human skin contains sensitive pain and touch receptors that trigger an "itch" sensation when poked by stiff fibers with a diameter greater than 28 microns. Traditional coarse sheep's wool fibers are thick (30 to 40 microns) and rigid, irritating skin nerve endings. In contrast, Saxon superfine merino wool fibers are ultra-fine (15.5 microns)&mdash;they are so thin and flexible that they simply bend softly when making contact with the skin, feeling silky, cloud-soft, and completely itch-free.
            </div>
          </div>
          <div class="faq-knit-item">
            <button class="faq-knit-btn">What is the functional advantage of a hand-linked toe over a machine-sewn toe? <span class="faq-toggle-icon">+</span></button>
            <div class="faq-knit-content">
              Standard commercial socks use automated sewing machines to stitch the toe closed, creating a thick, raised ridge of overlapping fabric and bulky thread. When pressed against the top of the toes inside dress shoes or athletic footwear, this ridge generates continuous pressure and friction, leading to blisters and toe irritation. Hand-linking connects every individual knit loop onto a radial dial by hand, knitting the toe closed with a single thread to produce a completely flat, weightless, zero-bulk seam.
            </div>
          </div>
          <div class="faq-knit-item">
            <button class="faq-knit-btn">How does needle count (168 vs 200 vs 240 needles) affect sock fabric quality? <span class="faq-toggle-icon">+</span></button>
            <div class="faq-knit-content">
              The needle count refers to the number of individual latch needles arranged around the circular cylinder of the knitting machine. A 96-needle machine knits thick, chunky heavy socks. A 168-needle machine produces standard casual socks. A 200-needle machine packs significantly more micro-loops into the same circumference, yielding an ultra-dense, lightweight, opaque fabric with higher recovery elasticity and refined texture suitable for bespoke tailoring.
            </div>
          </div>
          <div class="faq-knit-item">
            <button class="faq-knit-btn">What is the optimal method for washing and caring for luxury wool and cashmere hosiery? <span class="faq-toggle-icon">+</span></button>
            <div class="faq-knit-content">
              Fine wool and cashmere socks should be turned inside out and hand-washed or machine-washed on a gentle wool cycle in cool water (30&deg;C / 86&deg;F) using a pH-neutral, lanolin-replenishing wool shampoo. Never use chlorine bleach or fabric softeners. After washing, gently press out excess water in a towel and lay the socks flat to dry away from direct heat sources. Never tumble-dry luxury knitwear, as heat and agitation cause irreversible fiber shrinkage.
            </div>
          </div>
