          <span class="badge-knit">Biomechanical Engineering</span>
          <h2 style="font-size: 2.8rem; margin: 0.85rem 0 1.25rem;">The Micro-Biomechanics of Hand-Linked Seamless Toes</h2>
          <p style="font-size: 1.05rem; color: var(--text-knit-muted); line-height: 1.8;">
            Standard machine-made socks use automated overlock sewing (Rosso machine seams) to close the toe, leaving a bulky, raised ridge of thread that rubs continuously against the top of the toes inside footwear. Over 10,000 daily walking steps, this friction causes micro-abrasions, blisters, and nerve fatigue.
          </p>

          <div class="tech-cards-cluster">
            <div class="tech-micro-card">
              <h4>Loop-by-Loop Dial Linking</h4>
              <p>Every individual knitted loop is placed onto a circular needle bed by hand, stitching the seam shut with a single continuous thread.</p>
            </div>
            <div class="tech-micro-card">
              <h4>Zero-Friction Interior</h4>
              <p>Creates a 100% flat, weightless seam with zero millimeters of raised ridge, eliminating toe pressure points completely.</p>
            </div>
            <div class="tech-micro-card">
              <h4>Anatomical Y-Gore Heel</h4>
              <p>3D knitted reciprocal heel pocket with deep pocket depth preventing slipping, bunching, and heel blister friction.</p>
            </div>
            <div class="tech-micro-card">
              <h4>Targeted Arch Band</h4>
              <p>High-modulus Lycra ribbing woven across the plantar fascia to support the medial arch and prevent sock slippage.</p>
            </div>
          </div>
        </div>
